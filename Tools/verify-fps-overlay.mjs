import assert from 'node:assert/strict';
import { normalizedPoint, targetGeometry, translatedGeometry, resizedGeometry, movedSwipeEndpoint } from '../Sources/IControlApp/Resources/Viewer/fps-overlay.js';

const rect = { left: 120, top: 40, width: 640, height: 480 };
assert.deepEqual(normalizedPoint(440, 280, rect), { x: 0.5, y: 0.5 });
const action = normalizedPoint(696, 299.2, rect);
assert(Math.abs(action.x - 0.9) < 1e-10 && Math.abs(action.y - 0.54) < 1e-10);
assert.equal(normalizedPoint(119, 280, rect), null);
assert.equal(normalizedPoint(440, 521, rect), null);
assert.equal(normalizedPoint(NaN, 280, rect), null);
assert.equal(normalizedPoint(440, 280, { ...rect, width: 0 }), null);
assert.equal(normalizedPoint(440, 280, { ...rect, width: Infinity }), null);

const near = (actual, expected) => assert(Math.abs(actual - expected) < 1e-10, `${actual} != ${expected}`);
const actionGeometry = { x: 0.9, y: 0.54, size: 0.075 };
const moved = translatedGeometry(actionGeometry, -64, 48, rect);
near(moved.x, 0.8); near(moved.y, 0.64);
assert.deepEqual(translatedGeometry(actionGeometry, 9999, -9999, rect), { x: 1, y: 0, size: 0.075 });
assert.equal(translatedGeometry(actionGeometry, NaN, 0, rect), null);
const joystick = translatedGeometry({ x: 0.15, y: 0.76, radius: 0.18 }, -9999, -9999, rect);
near(joystick.x, 0.135); near(joystick.y, 0.18);
const portrait = translatedGeometry({ x: 0.5, y: 0.5, radius: 0.18 }, 9999, 9999, { ...rect, width: 360, height: 640 });
near(portrait.x, 0.68); near(portrait.y, 0.82);
const look = { x: 0.66, y: 0.43, width: 0.38, height: 0.52 };
const edge = translatedGeometry(look, 9999, 9999, rect);
near(edge.x, 0.81); near(edge.y, 0.74);

for (const handle of ['nw', 'ne', 'sw', 'se']) {
  const sx = handle.endsWith('e') ? 1 : -1, sy = handle.startsWith('s') ? 1 : -1;
  const resized = resizedGeometry(look, handle, sx * 64, sy * 48, rect);
  near(resized.width, 0.48); near(resized.height, 0.62);
  near(resized.x - sx * resized.width / 2, look.x - sx * look.width / 2);
  near(resized.y - sy * resized.height / 2, look.y - sy * look.height / 2);
  const limited = resizedGeometry(look, handle, sx * 9999, sy * 9999, rect);
  assert(limited.x - limited.width / 2 >= -1e-10 && limited.x + limited.width / 2 <= 1 + 1e-10);
  assert(limited.y - limited.height / 2 >= -1e-10 && limited.y + limited.height / 2 <= 1 + 1e-10);
  assert(limited.width <= 0.65 && limited.height <= 0.80);
}
const proportional = resizedGeometry(look, 'se', 60, 20, rect, true);
near(proportional.width / proportional.height, look.width / look.height);
const tiny = resizedGeometry(look, 'se', -9999, -9999, rect);
near(tiny.width, 0.10); near(tiny.height, 0.10);
const grownJoystick = resizedGeometry({ x: 0.15, y: 0.76, radius: 0.085 }, 'se', 24, 24, rect);
near(grownJoystick.radius, 0.135); near(grownJoystick.x, 0.15); near(grownJoystick.y, 0.76);
near(resizedGeometry({ x: 0.1, y: 0.9, radius: 0.085 }, 'se', 9999, 9999, rect).radius, 0.1);
near(resizedGeometry(actionGeometry, 'se', 24, 24, rect).size, 0.175);
near(resizedGeometry(actionGeometry, 'nw', 9999, 9999, rect).size, 0.04);
assert.equal(resizedGeometry(actionGeometry, 'bad', 10, 10, rect), null);
assert.equal(resizedGeometry(actionGeometry, 'se', 10, 10, { ...rect, height: 0 }), null);
assert.deepEqual(targetGeometry({ joystick: { x: 0.1, y: 0.2 }, radius: 0.08 }, 'joystick'), { x: 0.1, y: 0.2, radius: 0.08 });
assert.equal(targetGeometry({ bindings: [] }, 'missing'), null);
const customID = 'custom.598F9B2A-85E7-4421-8A22-0A924BA547D7';
const customProfile = { bindings: [{ id: customID, x: 0.36, y: 0.50, size: 0.12 }] };
const customGeometry = targetGeometry(customProfile, customID);
assert.deepEqual(customGeometry, { x: 0.36, y: 0.50, size: 0.12 });
const draggedCustom = translatedGeometry(customGeometry, 64, -48, rect);
near(draggedCustom.x, 0.46); near(draggedCustom.y, 0.40);
near(resizedGeometry(draggedCustom, 'se', 12, 12, rect).size, 0.17);
console.log('FPS overlay geometry passed: rendered-frame coordinates, drag offsets, screen bounds, portrait aspect, all resize corners, anchored look region, proportional resize, marker sizes and invalid input.');
const swipe = { x: 0.4, y: 0.7, endX: 0.4, endY: 0.3, size: 0.075 };
const swipeMoved = translatedGeometry(swipe, 64, -48, rect);
near(swipeMoved.x, 0.5); near(swipeMoved.y, 0.6); near(swipeMoved.endX, 0.5); near(swipeMoved.endY, 0.2);
const boundedSwipe = translatedGeometry(swipe, 9999, -9999, rect);
near(boundedSwipe.x, 1); near(boundedSwipe.endX, 1); near(boundedSwipe.y, 0.4); near(boundedSwipe.endY, 0);
const newEnd = movedSwipeEndpoint(swipe, -128, 48, rect);
near(newEnd.x, 0.4); near(newEnd.y, 0.7); near(newEnd.endX, 0.2); near(newEnd.endY, 0.4);
assert.deepEqual(movedSwipeEndpoint(swipe, 0, 192, rect), swipe);
assert.equal(movedSwipeEndpoint(swipe, NaN, 0, rect), null);
assert.deepEqual(targetGeometry({ bindings: [{ id: customID, ...swipe }] }, customID), swipe);
console.log('Swipe endpoint drag, whole-path translation, bounds and degenerate-path rejection passed.');
